/** Pixels allumés d'un texte, en coordonnées de police (1 = un pixel de police). */
export function pixelsTexte(texte: string): { points: [number, number][]; largeur: number } {
  const points: [number, number][] = [];
  let x = 0;
  for (const car of texte.toUpperCase()) {
    const g = G[car];
    if (!g) throw new Error(`Caractère absent de la police pixel : « ${car} »`);
    g.forEach((ligne, y) => [...ligne].forEach((p, dx) => p === '#' && points.push([x + dx, y])));
    x += g[0]!.length + 1;
  }
  return { points, largeur: Math.max(0, x - 1) };
}
